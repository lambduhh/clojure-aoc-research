(ns research.core-vars
  "When each public var in Clojure's own namespaces was added, straight from
  the vars' metadata (e.g. parse-long -> \"1.11\"). Writes data/core-vars.edn."
  (:require [clojure.string :as str]))

(def namespaces
  '[clojure.core clojure.string clojure.set clojure.walk clojure.zip clojure.edn
    clojure.math clojure.data clojure.pprint clojure.java.io clojure.test clojure.repl])

(defn -main [& _]
  (run! require namespaces)
  (let [rows (into (sorted-map)
                   (for [ns-sym namespaces
                         [sym v] (ns-publics ns-sym)
                         :let [{:keys [added macro]} (meta v)]]
                     [(str ns-sym "/" sym) (cond-> {:added (or added (-> ns-sym the-ns meta :added))}
                                             macro (assoc :macro true))]))]
    (spit "data/core-vars.edn"
          (str ";; Generated by research.core-vars on Clojure " (clojure-version) "\n"
               "{\n" (str/join "\n" (map (fn [[k v]] (str (pr-str k) " " (pr-str v))) rows)) "\n}\n"))
    (println (count rows) "vars ->" "data/core-vars.edn"
             "| by version:" (into (sorted-map) (frequencies (map :added (vals rows)))))))
